def build_cases() -> list[dict]:
    cases = []
    for kind, items in SINGLE.items():
        for i, (u, mem) in enumerate(items):
            cases.append({"id": f"{kind}_{i}", "kind": kind, "memory": mem, "history": [], "user": u})
    for cid, mem, hist, u in MULTI:
        cases.append({"id": f"multi_{cid}", "kind": "multi", "memory": mem,
                      "history": [{"role": r, "content": c} for r, c in hist], "user": u})
    for cid, u, lines, hours in RECAP:
        cases.append({"id": cid, "kind": "recap", "memory": [], "history": [], "user": u, "recap": [lines, hours]})
    return cases
