def pick_lang(lang: str | None, accept: str | None) -> str:
    raw = (lang or accept or "").lower()
    return "en" if raw.startswith("en") else "zh-CN"


def _page(title: str, body: str, lang: str = "zh-CN") -> HTMLResponse:
    return HTMLResponse(f"<!doctype html><html lang={lang}><meta charset=utf-8><meta name=viewport content='width=device-width'><title>{title}</title><style>{_STYLE}</style>{body}")


def register_legal(app: FastAPI) -> None:
    def privacy(lang: str | None = None, accept_language: str | None = Header(default=None)) -> HTMLResponse:
        en = pick_lang(lang, accept_language) == "en"
        return _page("olo Privacy Policy" if en else "olo 隐私政策", PRIVACY_EN if en else PRIVACY, "en" if en else "zh-CN")

    def terms(lang: str | None = None, accept_language: str | None = Header(default=None)) -> HTMLResponse:
        en = pick_lang(lang, accept_language) == "en"
        return _page("olo Terms of Use" if en else "olo 使用条款", TERMS_EN if en else TERMS, "en" if en else "zh-CN")

    app.add_api_route("/privacy", privacy, methods=["GET"], include_in_schema=False)
    app.add_api_route("/terms", terms, methods=["GET"], include_in_schema=False)
