# 大约每 4 轮给一次「可以提一件自己的小事」的机会。
DAILY_LIFE_EVERY = 4


def story_slice(level: int | None, turn_index: int | None) -> str:
    """当前阶段关系 + （偶尔）一件 olo 自己的日常。保持很短。"""
    lines = [CAST_LINE]
    if level in STAGE_RELATION:
        lines.append("【你们的关系】" + STAGE_RELATION[level])
    if turn_index is not None and turn_index % DAILY_LIFE_EVERY == DAILY_LIFE_EVERY - 1:
        detail = DAILY_LIFE[(turn_index // DAILY_LIFE_EVERY) % len(DAILY_LIFE)]
        lines.append(
            "【你自己今天的小事】" + detail
            + "如果话题合适（对方不在难过、不在说正事），可以顺口提一句；不合适就不提。"
            "这是你自己的日子，不是你们之间的回忆。"
        )
    return "\n".join(lines)
