"""Render the web pixel olo (web/pixel.js drawOlo) into sprite sheets for the mobile app.

Usage: python scripts/gen_mobile_sprites.py   (needs playwright + chromium; Pillow shrinks the layer PNGs)
Output: apps/mobile/assets/olo/<form>-<state>.png, FRAMES frames of 32x32 scaled ×SCALE, side by side.
Accessory layers: apps/mobile/assets/olo/layers/<form>-<state>-<kind>-<value>.png hold only the pixels that
differ from the default look (transparent elsewhere); Character.tsx stacks them over the base sheet.
The require map is written to apps/mobile/src/oloLayers.ts.
"""

import base64
import functools
import http.server
import threading
from pathlib import Path

from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "apps/mobile/assets/olo"
LAYER_OUT = OUT / "layers"
FORMS = {"buddy": "sun", "cloud": "sky", "glow": "lavender"}  # same as web FORM_COLOR
STATES = ["idle", "happy", "talking", "sad", "thinking", "held", "sleep"]
LAYERS = {
    "hair": ["bow", "leaf", "spikes", "curl", "crest", "bun", "sun", "halo", "straw"],
    "eyes": ["almond"],
    "cheeks": ["dots", "triangle", "warpaint", "none"],
}
FRAMES, SCALE, PERIOD = 12, 8, 26.0  # PERIOD in drawOlo t units (10 = 1 s)

JS = """
async ([form, color, state, frames, scale, period, extra]) => {
  const { drawOlo } = await import('/pixel.js');
  const src = document.createElement('canvas'); src.width = src.height = 32;
  const sctx = src.getContext('2d');
  const out = document.createElement('canvas'); out.width = 32 * scale * frames; out.height = 32 * scale;
  const octx = out.getContext('2d'); octx.imageSmoothingEnabled = false;
  for (let i = 0; i < frames; i++) {
    const t = 3 + i * period / frames;
    sctx.clearRect(0, 0, 32, 32);
    if (extra) {
      drawOlo(sctx, { form, color, state, t });
      const base = sctx.getImageData(0, 0, 32, 32);
      sctx.clearRect(0, 0, 32, 32);
      drawOlo(sctx, { form, color, state, t, ...extra });
      const img = sctx.getImageData(0, 0, 32, 32), a = img.data, b = base.data;
      let any = false;
      for (let k = 0; k < a.length; k += 4) {
        if (a[k] === b[k] && a[k + 1] === b[k + 1] && a[k + 2] === b[k + 2] && a[k + 3] === b[k + 3]) a[k + 3] = 0;
        else any = true;
      }
      sctx.putImageData(img, 0, 0);
    } else drawOlo(sctx, { form, color, state, t });
    octx.drawImage(src, 0, 0, 32, 32, i * 32 * scale, 0, 32 * scale, 32 * scale);
  }
  return out.toDataURL('image/png');
}
"""


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    LAYER_OUT.mkdir(parents=True, exist_ok=True)
    layers: list = []
    handler = functools.partial(http.server.SimpleHTTPRequestHandler, directory=str(ROOT / "web"))
    httpd = http.server.ThreadingHTTPServer(("127.0.0.1", 0), handler)
    threading.Thread(target=httpd.serve_forever, daemon=True).start()
    port = httpd.server_address[1]
    with sync_playwright() as p:
        browser = p.chromium.launch()
        page = browser.new_page()
        page.emulate_media(reduced_motion="no-preference")
        page.goto(f"http://127.0.0.1:{port}/fonts/README.md")
        for form, color in FORMS.items():
            for state in STATES:
                url = page.evaluate(JS, [form, color, state, FRAMES, SCALE, PERIOD, None])
                (OUT / f"{form}-{state}.png").write_bytes(base64.b64decode(url.split(",", 1)[1]))
                for kind, values in LAYERS.items():
                    for value in values:
                        url = page.evaluate(JS, [form, color, state, FRAMES, SCALE, PERIOD, {kind: value}])
                        name = f"{form}-{state}-{kind}-{value}"
                        save_small(LAYER_OUT / f"{name}.png", base64.b64decode(url.split(",", 1)[1]))
                        layers.append((form, state, kind, value, name))
        browser.close()
    httpd.shutdown()
    write_map(layers)
    print(f"wrote {len(FORMS) * len(STATES)} sheets + {len(layers)} accessory layers to {OUT}")


def save_small(path: Path, png: bytes) -> None:
    """Layers are mostly transparent with few colours: a palette PNG keeps the app small (~1–2 KB each)."""
    import io

    try:
        from PIL import Image
    except ImportError:  # works without Pillow, just bigger files
        path.write_bytes(png)
        return
    Image.open(io.BytesIO(png)).quantize(colors=64, method=Image.Quantize.FASTOCTREE).save(path, optimize=True)


def write_map(layers: list) -> None:
    lines = [
        "// Generated by scripts/gen_mobile_sprites.py — do not edit.",
        'import { ImageSourcePropType } from "react-native";',
        "",
        "/* eslint-disable @typescript-eslint/no-require-imports */",
        "export const LAYERS: Record<string, ImageSourcePropType> = {",
    ]
    for form, state, kind, value, name in layers:
        lines.append(f'  "{form}/{state}/{kind}/{value}": require("../assets/olo/layers/{name}.png"),')
    lines += ["};", ""]
    (ROOT / "apps/mobile/src/oloLayers.ts").write_text("\n".join(lines))


if __name__ == "__main__":
    main()
