"""Render the 2.5D 雾里集 plaza (web/room.js) into layered PNGs for the mobile Room screen.

Usage: python scripts/gen_mobile_room.py   (needs playwright + chromium; Pillow shrinks the PNGs)
Output: apps/mobile/assets/room/<daypart>-floor.png (walls + floor + lighting) and
<daypart>-<prop>.png (one prop each, same full frame) at RW×RH ×SCALE, plus src/roomAssets.ts.
Room.tsx stacks props and olo by depth (wx+wy) with the same iso numbers as room.js geometry().
"""

import base64
import functools
import http.server
import io
import json
import threading
from pathlib import Path

from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "apps/mobile/assets/room"
RW, RH, SCALE = 200, 170, 4
HOURS = {"dawn": 6.3, "day": 12.0, "dusk": 18.2, "night": 23.0}

JS = """
async ([hour, RW, RH, scale]) => {
  const R = await import('/room.js');
  const L = R.light(hour);
  const src = document.createElement('canvas'); src.width = RW; src.height = RH;
  const ctx = src.getContext('2d'); ctx.imageSmoothingEnabled = false;
  const big = (fn) => {
    ctx.clearRect(0, 0, RW, RH); fn();
    const o = document.createElement('canvas'); o.width = RW * scale; o.height = RH * scale;
    const oc = o.getContext('2d'); oc.imageSmoothingEnabled = false; oc.drawImage(src, 0, 0, RW * scale, RH * scale);
    return o.toDataURL('image/png');
  };
  const G = R.geometry(RW, RH);
  const tint = () => {
    ctx.globalCompositeOperation = 'source-atop';
    if (L.night > 0.05) { ctx.globalAlpha = 0.38 * L.night; ctx.fillStyle = '#141838'; ctx.fillRect(0, 0, RW, RH); }
    else if (L.dusk) { ctx.globalAlpha = 0.14; ctx.fillStyle = L.sk.phase === 'dusk' ? '#ff7a3a' : '#ff9ab0'; ctx.fillRect(0, 0, RW, RH); }
    ctx.globalAlpha = 1; ctx.globalCompositeOperation = 'source-over';
  };
  const out = { phase: L.sk.phase, floor: big(() => { R.drawBackdrop(ctx, RW, RH, L, 0, false); R.drawLighting(ctx, RW, RH, L, 0); }), props: {} };
  for (const q of R.PROPS) out.props[q.id] = big(() => { const [X, Y] = G.proj(q.x, q.y); R.drawProp(ctx, q.id, X, Y, L, 0); tint(); });
  out.geo = { ox: G.ox, oy: G.oy };
  return out;
}
"""


def save(path: Path, url: str) -> None:
    png = base64.b64decode(url.split(",", 1)[1])
    try:
        from PIL import Image
        Image.open(io.BytesIO(png)).quantize(colors=128, method=Image.Quantize.FASTOCTREE).save(path, optimize=True)
    except ImportError:
        path.write_bytes(png)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    handler = functools.partial(http.server.SimpleHTTPRequestHandler, directory=str(ROOT / "web"))
    httpd = http.server.ThreadingHTTPServer(("127.0.0.1", 0), handler)
    threading.Thread(target=httpd.serve_forever, daemon=True).start()
    port = httpd.server_address[1]
    lines = [
        "// Generated by scripts/gen_mobile_room.py — do not edit.",
        'import { ImageSourcePropType } from "react-native";',
        "",
        f"export const ROOM = {{ RW: {RW}, RH: {RH} }};",
        "/* eslint-disable @typescript-eslint/no-require-imports */",
        "export const ROOM_LAYERS: Record<string, { floor: ImageSourcePropType; props: Record<string, ImageSourcePropType> }> = {",
    ]
    props_meta = None
    with sync_playwright() as p:
        browser = p.chromium.launch()
        page = browser.new_page()
        page.goto(f"http://127.0.0.1:{port}/fonts/README.md")
        for part, hour in HOURS.items():
            r = page.evaluate(JS, [hour, RW, RH, SCALE])
            save(OUT / f"{part}-floor.png", r["floor"])
            for pid, url in r["props"].items():
                save(OUT / f"{part}-{pid}.png", url)
            props = ", ".join(f'{pid}: require("../assets/room/{part}-{pid}.png")' for pid in r["props"])
            lines.append(f'  {part}: {{ floor: require("../assets/room/{part}-floor.png"), props: {{ {props} }} }},')
        props_meta = page.evaluate("async () => (await import('/room.js')).PROPS")
        browser.close()
    httpd.shutdown()
    lines += ["};", "", f"export const PROPS: {{ id: string; x: number; y: number; r: number; h: number }}[] = {json.dumps(props_meta)};", ""]
    (ROOT / "apps/mobile/src/roomAssets.ts").write_text("\n".join(lines))
    print("wrote", len(HOURS), "dayparts to", OUT)


if __name__ == "__main__":
    main()
